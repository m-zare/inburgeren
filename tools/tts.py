"""Generates spoken audio for every sentence and word the app can play.

Uses the open-source Piper voice nl_NL-ronnie-medium (CC0) through
sherpa-onnx, and writes audio/<id>.mp3 plus audio/index.js, which maps each
spoken text to its file. Existing files are reused, so a rerun after editing
content only renders new texts.

Setup (once):
  python3 -m venv .venv && .venv/bin/pip install sherpa-onnx numpy lameenc
  curl -LO https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/vits-piper-nl_NL-ronnie-medium.tar.bz2
  tar xjf vits-piper-nl_NL-ronnie-medium.tar.bz2

Usage (from the project root, after `node tools/build.js`):
  .venv/bin/python tools/tts.py --model path/to/vits-piper-nl_NL-ronnie-medium
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

import lameenc
import numpy as np
import sherpa_onnx

ROOT = Path(__file__).resolve().parent.parent
AUDIO_DIR = ROOT / "audio"
PUNCT = re.compile(r"[.,!?;:\"“”]")


def load_data():
    """Reads TOPICS/EXERCISES/WORDS from data.js (JSON after each `const X =`)."""
    src = (ROOT / "data.js").read_text()
    data = {}
    for name in ("EXERCISES", "WORDS"):
        start = src.index(f"const {name} = ") + len(f"const {name} = ")
        end = src.index(";\n", start)
        data[name] = json.loads(src[start:end])
    return data["EXERCISES"], data["WORDS"]


def spoken_texts(exercises, words):
    """The exact strings app.js passes to speak(), mirroring its logic.
    Returns {text: is_sentence}."""
    plain = lambda key: key.split("@")[0]
    texts = {}
    for ex in exercises:
        texts[ex["answer"]] = True
        for token in PUNCT.sub(" ", ex["answer"].lower()).split():
            key = ex.get("senses", {}).get(token, token)
            entry = words.get(key)
            word = lemma = plain(key)
            if entry and entry.get("see"):
                lemma = plain(entry["see"])
                entry = words.get(entry["see"])
            title = f"{entry['article']} {lemma}" if entry and entry.get("article") else lemma
            texts.setdefault(title, False)
            if word != lemma:
                texts.setdefault(word, False)
    return dict(sorted(texts.items()))


def tts_input(text, is_sentence):
    """Sentences read better with a capital and closing punctuation."""
    if is_sentence:
        text = text[0].upper() + text[1:]
        if text[-1] not in ".?!":
            text += "."
    return text


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", required=True, help="vits-piper-nl_NL-ronnie-medium directory")
    parser.add_argument("--speed", type=float, default=0.9, help="1.0 = normal; lower is slower")
    args = parser.parse_args()

    model = Path(args.model)
    name = model.name.removeprefix("vits-piper-")
    tts = sherpa_onnx.OfflineTts(
        sherpa_onnx.OfflineTtsConfig(
            model=sherpa_onnx.OfflineTtsModelConfig(
                vits=sherpa_onnx.OfflineTtsVitsModelConfig(
                    model=str(model / f"{name}.onnx"),
                    tokens=str(model / "tokens.txt"),
                    data_dir=str(model / "espeak-ng-data"),
                ),
                num_threads=4,
            )
        )
    )

    AUDIO_DIR.mkdir(exist_ok=True)
    exercises, words = load_data()
    index = {}
    created = 0
    for text, is_sentence in spoken_texts(exercises, words).items():
        # The id covers voice and speed, so changing either re-renders.
        file_id = hashlib.sha1(f"{name}|{args.speed}|{text}".encode()).hexdigest()[:12]
        index[text] = file_id
        path = AUDIO_DIR / f"{file_id}.mp3"
        if path.exists():
            continue
        audio = tts.generate(tts_input(text, is_sentence), sid=0, speed=args.speed)
        pcm = (np.clip(np.array(audio.samples), -1, 1) * 32767).astype("<i2")
        enc = lameenc.Encoder()
        enc.set_bit_rate(40)
        enc.set_in_sample_rate(audio.sample_rate)
        enc.set_channels(1)
        enc.set_quality(2)
        path.write_bytes(enc.encode(pcm.tobytes()) + enc.flush())
        created += 1

    (AUDIO_DIR / "index.js").write_text(
        "// Generated by tools/tts.py: spoken text -> audio/<id>.mp3\n"
        f"const AUDIO = {json.dumps(index, ensure_ascii=False, indent=0)};\n"
    )
    used = {f"{i}.mp3" for i in index.values()}
    unused = [p.name for p in AUDIO_DIR.glob("*.mp3") if p.name not in used]
    print(f"{len(index)} texts, {created} new files, {len(unused)} unused files in audio/")


if __name__ == "__main__":
    main()
