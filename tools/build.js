// Merges content/*.json into data.js (loaded by index.html).
// Usage: node tools/build.js
const fs = require("fs");
const path = require("path");

const TOPICS = [
  { id: "werk", name: "Werk" },
  { id: "school", name: "School & cursus" },
  { id: "wonen", name: "Wonen & buurt" },
  { id: "winkelen", name: "Winkelen & eten" },
  { id: "gezondheid", name: "Gezondheid & instanties" },
  { id: "vrije-tijd", name: "Vrije tijd & familie" },
];

// Grammar groups, from easiest to hardest (keep in sync with tools/check.js).
const GRAMMAR = [
  { id: "basis", name: "Basic order", info: "Subject – verb – rest. After the verb: time, manner, place." },
  { id: "inversie", name: "Inversion", info: "Something else comes first, so the verb comes before the subject." },
  { id: "vraag", name: "Questions & commands", info: "The verb comes first, or right after the question word." },
  { id: "modaal", name: "Modal verb + infinitive", info: "kunnen, moeten, willen, mogen, gaan … in 2nd place, the infinitive at the end." },
  { id: "scheidbaar", name: "Separable verbs", info: "The verb is 2nd, its particle (op, mee, aan …) goes to the end." },
  { id: "perfectum", name: "Perfect tense", info: "heeft/is in 2nd place, the past participle (ge…) at the end." },
  { id: "nevenschikkend", name: "Two main clauses", info: "en, maar, want, of, dus: both parts keep normal main-clause order." },
  { id: "om-te", name: "om … te + infinitive", info: "te + infinitive at the end of the phrase." },
  { id: "bijzin", name: "Subordinate clause", info: "After omdat, dat, als, die … the verbs go to the end." },
];

const exercises = [];
const words = {};
const files = fs.readdirSync("content").filter((f) => f.endsWith(".json")).sort();
const contents = files.map((f) => JSON.parse(fs.readFileSync(path.join("content", f), "utf8")));

// First file wins, so content/00-basis.json can override.
for (const data of contents) {
  for (const [k, v] of Object.entries(data.words || {})) words[k] ??= v;
}

const tokenize = (s) => s.toLowerCase().replace(/[.,!?;:"“”]/g, " ").split(/\s+/).filter(Boolean);
// Two entries mean the same thing if they point to the same base word,
// or have the same type, article and gloss.
const sig = (e) => (e.see ? "see:" + e.see : [e.type, e.article, e.en].join("|"));

contents.forEach((data, i) => {
  const prefix = files[i].split("-")[0];
  const own = data.words || {};
  // A sentence's words are explained by its own file's entries. When those
  // differ from the shared entry (homonyms: "staat" = condition vs stands),
  // store the file's entry under "word@file" and point the sentence at it.
  const senseKey = (t) => {
    const e = own[t];
    if (!e || sig(e) === sig(words[t])) return null;
    const key = `${t}@${prefix}`;
    words[key] = e.see ? { ...e, see: senseKey(e.see) || e.see } : e;
    return key;
  };
  for (const ex of data.exercises || []) {
    const senses = {};
    for (const t of tokenize(ex.answer)) {
      const key = senseKey(t);
      if (key) senses[t] = key;
    }
    exercises.push({
      id: ex.id,
      topic: ex.topic,
      parts: ex.parts,
      answer: ex.answer,
      alternatives: ex.alternatives || [],
      hint: ex.hint,
      grammar: ex.grammar,
      level: ex.level,
      ...(Object.keys(senses).length && { senses }),
    });
  }
});

// Per topic: grammar groups from easy to hard, then easy to hard inside a
// group (level, then sentence length).
const topicOrder = TOPICS.map((t) => t.id);
const grammarOrder = GRAMMAR.map((g) => g.id);
const length = (ex) => tokenize(ex.answer).length;
exercises.sort(
  (a, b) =>
    topicOrder.indexOf(a.topic) - topicOrder.indexOf(b.topic) ||
    grammarOrder.indexOf(a.grammar) - grammarOrder.indexOf(b.grammar) ||
    a.level - b.level ||
    length(a) - length(b)
);

const out =
  "// Generated by tools/build.js from content/*.json — edit those files instead.\n" +
  `const TOPICS = ${JSON.stringify(TOPICS, null, 2)};\n\n` +
  `const GRAMMAR = ${JSON.stringify(GRAMMAR, null, 2)};\n\n` +
  `const EXERCISES = ${JSON.stringify(exercises, null, 1)};\n\n` +
  `const WORDS = ${JSON.stringify(words, null, 1)};\n`;
fs.writeFileSync("data.js", out);
console.log(`data.js: ${exercises.length} exercises, ${Object.keys(words).length} words`);
